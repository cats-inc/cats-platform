import './helpers/installDomBeforeReact.ts';
import assert from 'node:assert/strict';
import test from 'node:test';
import React from 'react';
import { act, cleanup, fireEvent, render } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter } from 'react-router-dom';
import { I18nProvider } from '../src/app/renderer/i18n/index.ts';
import { OwnerRecordActions } from '../src/products/shared/renderer/OwnerRecordActions.tsx';

test('owner actions display source blockers and require acceptance evidence with the preview token', async t => {
  const oldReact = Object.getOwnPropertyDescriptor(globalThis, 'React'), oldFetch = globalThis.fetch;
  Object.defineProperty(globalThis, 'React', { configurable: true, value: React });
  t.after(() => { cleanup(); globalThis.fetch = oldFetch; if (oldReact) Object.defineProperty(globalThis, 'React', oldReact); else Reflect.deleteProperty(globalThis, 'React'); });
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } }); t.after(() => client.clear());
  const view = { family: 'task', id: 't', token: 'bound-token', title: 'Task', summary: null, status: 'draft', source: 'core', listing: 'visible', sourcePath: '/chat/chats/source', assignedActorIds: [], projectId: null, parentId: null, priority: '', acceptanceCriteria: 'Test passes', dependencies: [], choices: { projects: [], parents: [], actors: [] }, actions: [{ action: 'edit', blockers: ['Source control only.'] }, { action: 'complete', blockers: [] }] };
  let command: any;
  globalThis.fetch = async (_url, options) => { if (options?.body) command = JSON.parse(String(options.body)); return new Response(JSON.stringify(options?.body ? { removed: false, view: { ...view, status: 'completed' } } : view), { status: 200 }); };
  let ui: ReturnType<typeof render>;
  await act(async () => { ui = render(<QueryClientProvider client={client}><MemoryRouter><I18nProvider locale="en"><OwnerRecordActions family="task" id="t" expanded /></I18nProvider></MemoryRouter></QueryClientProvider>); });
  assert.ok(ui!.getByText('Source control only.'));
  assert.equal(ui!.getByText('Open source conversation').getAttribute('href'), '/chat/chats/source');
  fireEvent.change(ui!.getByRole('combobox', { name: 'Actions' }), { target: { value: 'complete' } });
  assert.equal((ui!.getByText('Apply') as HTMLButtonElement).disabled, true);
  fireEvent.click(ui!.getByLabelText('I reviewed the acceptance criteria'));
  fireEvent.change(ui!.getByLabelText('Acceptance evidence'), { target: { value: 'Targeted tests passed' } });
  await act(async () => { fireEvent.submit(ui!.getByText('Apply').closest('form')!); });
  assert.equal(command.token, 'bound-token');
  assert.equal(command.acceptanceConfirmed, true);
  assert.equal(command.acceptanceNote, 'Targeted tests passed');
});
